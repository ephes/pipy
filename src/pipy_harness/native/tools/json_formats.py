_DAYS = (0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31)
_DATE = re.compile(r"(\d\d\d\d)-(\d\d)-(\d\d)", re.ASCII)
_TIME = re.compile(
    r"(\d\d):(\d\d):(\d\d)(?:\.\d+)?(?:([Zz])|([+-])(\d\d):(\d\d))?", re.ASCII
)
_MINUTES_PER_DAY = 1440


def _is_date(value: str) -> bool:
    """TypeBox ``IsDate``: RFC 3339 ``full-date`` with the month's days."""

    match = _DATE.fullmatch(value)
    if match is None:
        return False
    year, month, day = (int(part) for part in match.groups())
    leap = year % 4 == 0 and (year % 100 != 0 or year % 400 == 0)
    if not 1 <= month <= 12:
        return False
    return 1 <= day <= (29 if month == 2 and leap else _DAYS[month])


def _is_time(value: str) -> bool:
    """TypeBox ``IsTime`` (strict time zone): RFC 3339 ``full-time``; a leap
    second only at 23:59:60 UTC."""

    match = _TIME.fullmatch(value)
    if match is None or not (match.group(4) or match.group(5)):
        return False
    hour, minute, second = (int(match.group(index)) for index in (1, 2, 3))
    if hour > 23 or minute > 59 or second > 60:
        return False
    offset_hours = int(match.group(6) or 0)
    offset_minutes = int(match.group(7) or 0)
    if match.group(5) and (offset_hours > 23 or offset_minutes > 59):
        return False
    if second < 60:
        return True
    sign = -1 if match.group(5) == "-" else 1
    utc = hour * 60 + minute - sign * (offset_hours * 60 + offset_minutes)
    return utc % _MINUTES_PER_DAY == _MINUTES_PER_DAY - 1


def _is_date_time(value: str) -> bool:
    """TypeBox ``IsDateTime``: a date and a time around one ``T``."""

    parts = re.split("[Tt]", value)
    return len(parts) == 2 and _is_date(parts[0]) and _is_time(parts[1])


def _full_match(pattern: re.Pattern[str]) -> Callable[[str], bool]:
    return lambda value: pattern.fullmatch(value) is not None


_CHECKS: dict[str, Callable[[str], bool]] = {
    "date": _is_date,
    "time": _is_time,
    "date-time": _is_date_time,
    **{name: _full_match(pattern) for name, pattern in _PATTERNS.items()},
}


def format_matches(name: str, value: str) -> bool:
    """Whether ``value`` has the format ``name``; a format pipy does not
    check, or one TypeBox does not know, matches (TypeBox ``Format.Test``)."""

    check = _CHECKS.get(name)
    return True if check is None else check(value)
